        # "Default encoding set to utf-8"), поэтому кириллица в лог проходит. Здесь текст английский по другой причине:
        # диагностические строки удобнее грепать, и они одинаково читаются
        # в любой консоли. Опасен только py2-str в НЕ utf-8 кодировке -
        # например сырой путь из os.getcwd() на русской Windows.
